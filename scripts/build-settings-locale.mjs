/**
 * Builds src/services/settings/settingsI18n<Locale>.ts from the canonical EN key set
 * (scripts/settings-i18n-en-source.mjs) plus a locale's flat translation map
 * (scripts/settings-i18n-<locale>-partial.mjs). Generalization of the original
 * build-settings-tr.mjs so every non-English Settings locale is built the same way.
 *
 * Usage: node scripts/build-settings-locale.mjs <locale>   e.g. de, fr, es, it, pt, nl, pl, ru
 */
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadEnSettingsSource } from "./settings-i18n-en-source.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const locale = process.argv[2];
const LOCALES = { tr: "Tr", de: "De", fr: "Fr", es: "Es", it: "It", pt: "Pt", nl: "Nl", pl: "Pl", ru: "Ru" };
if (!locale || !LOCALES[locale]) {
  console.error(`Usage: node scripts/build-settings-locale.mjs <locale>\nSupported: ${Object.keys(LOCALES).join(", ")}`);
  process.exit(1);
}
const Pascal = LOCALES[locale];

const partialPath = path.join(root, `scripts/settings-i18n-${locale}-partial.mjs`);
const { default: localeMap } = await import(pathToFileURL(partialPath).href);

const enCatalog = loadEnSettingsSource();
const keys = Object.keys(enCatalog).sort();

// Same allowlist convention as build-settings-tr.mjs: keys/value-shapes legitimately
// identical across locales (brand names, URLs, key-cap combos, raw enum-ish values).
const MIRROR_KEY_ALLOW = new Set([
  "appearance.option.langEn",
  "appearance.option.langDe",
  "appearance.option.langFr",
  "appearance.option.langEs",
  "appearance.option.langIt",
  "appearance.option.langPt",
  "appearance.option.langNl",
  "appearance.option.langPl",
  "appearance.option.langRu",
  "appearance.option.langTr",
  "account.centerHelp",
  "legal.footer",
  // "Creator"/"Publisher" are product-tier proper nouns kept in English in every
  // locale (see docs/i18n/terminology-glossary.md); this section title is the
  // English pair with no natural translated form.
  "account.publisherTitle",
  // "PICOM Verified" is the product's brand name for its verification/subscription
  // program; kept in English in every locale.
  "verified.title",
]);
const MIRROR_VALUE_ALLOW =
  /^(https?:\/\/|Picom|Supabase|LiveKit|Electron|Windows|Linux|macOS|Chromium|RLS|MVP|CI\/|VITE_|Ctrl \+ Shift|Developer Portal|Companion|English|Türkçe|Deutsch|Français|Español|Italiano|Português|Nederlands|Polski|Русский|—|\d|\{|\}|%|·|@|#|Debug|Info|Warn|Error|online|main|companion|app|system|light|dark|left|right|top|bottom)/;

const missing = [];
const mirrored = [];
const emptyOrBlank = [];

for (const key of keys) {
  const enVal = enCatalog[key];
  const localeVal = localeMap[key];
  if (localeVal === undefined) {
    missing.push(key);
    continue;
  }
  if (typeof localeVal !== "string" || !localeVal.trim()) {
    emptyOrBlank.push(key);
    continue;
  }
  if (MIRROR_KEY_ALLOW.has(key)) continue;
  if (enVal === localeVal && /\s/.test(enVal) && enVal.length > 8 && !MIRROR_VALUE_ALLOW.test(enVal)) {
    mirrored.push(key);
  }
}

assert.equal(missing.length, 0, `Missing ${locale.toUpperCase()} for keys (${missing.length}): ${missing.slice(0, 20).join(", ")}${missing.length > 20 ? "…" : ""}`);
assert.equal(emptyOrBlank.length, 0, `Blank ${locale.toUpperCase()} value for keys: ${emptyOrBlank.slice(0, 20).join(", ")}`);
assert.equal(mirrored.length, 0, `${locale.toUpperCase()} mirrors EN verbatim for (${mirrored.length}): ${mirrored.slice(0, 20).join(", ")}${mirrored.length > 20 ? "…" : ""}`);

// Interpolation-token parity: every {param} in the EN string must also appear in the translation.
const tokenMismatch = [];
for (const key of keys) {
  const enTokens = [...enCatalog[key].matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
  const localeTokens = [...localeMap[key].matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
  if (JSON.stringify(enTokens) !== JSON.stringify(localeTokens)) tokenMismatch.push(key);
}
assert.equal(tokenMismatch.length, 0, `Interpolation token mismatch for keys: ${tokenMismatch.slice(0, 20).join(", ")}`);

const out = path.join(root, `src/services/settings/settingsI18n${Pascal}.ts`);
const lines = keys.map((key) => {
  const value = localeMap[key].replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `  "${key}": "${value}",`;
});

writeFileSync(
  out,
  `/** Auto-generated by scripts/build-settings-locale.mjs ${locale} — do not edit by hand; edit scripts/settings-i18n-${locale}-partial.mjs instead. */
import type { SettingsI18nKey } from "./settingsI18n";

export const settingsI18n${Pascal}: Record<SettingsI18nKey, string> = {
${lines.join("\n")}
};
`,
);

console.log(`built settingsI18n${Pascal}.ts: ${keys.length} keys`);
