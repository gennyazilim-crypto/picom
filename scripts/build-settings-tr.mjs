/**
 * Builds src/services/settings/settingsI18nTr.ts from EN keys + Turkish catalog.
 */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import trMap from "./settings-i18n-tr-map.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const i18nFile = path.join(root, "src/services/settings/settingsI18n.ts");
const modalFile = path.join(root, "src/services/settings/settingsModalEn.ts");
const trOut = path.join(root, "src/services/settings/settingsI18nTr.ts");

function parseEnStrings(tsSource) {
  const enMatch = tsSource.match(/const en = \{([\s\S]*?)\} as const;/);
  if (!enMatch) throw new Error("en block not found");
  return Object.fromEntries(
    [...enMatch[1].matchAll(/"([^"]+)":\s*"((?:\\.|[^"\\])*)"/g)].map((m) => [
      m[1],
      m[2].replace(/\\"/g, '"').replace(/\\\\/g, "\\"),
    ]),
  );
}

function parseModalStrings(tsSource) {
  return Object.fromEntries(
    [...tsSource.matchAll(/"([^"]+)":\s*\n?\s*"((?:\\.|[^"\\])*)"/g)].map((m) => [
      m[1],
      m[2].replace(/\\"/g, '"').replace(/\\\\/g, "\\"),
    ]),
  );
}

const baseEn = parseEnStrings(readFileSync(i18nFile, "utf8"));
const modalEn = parseModalStrings(readFileSync(modalFile, "utf8"));
const enCatalog = { ...baseEn, ...modalEn };
const keys = Object.keys(enCatalog).sort();

const MIRROR_KEY_ALLOW = new Set(["appearance.option.langEn", "account.centerHelp", "legal.footer"]);
const MIRROR_VALUE_ALLOW =
  /^(https?:\/\/|Picom|Supabase|LiveKit|Electron|Windows|Linux|macOS|Chromium|RLS|MVP|CI\/|VITE_|Ctrl \+ Shift|Developer Portal|Companion|English|Türkçe|—|\d|\{|\}|%|·|@|#|Debug|Info|Warn|Error|online|main|companion|app|system|light|dark|left|right|top|bottom)/;

const mirrored = [];
const missing = [];

for (const key of keys) {
  const enVal = enCatalog[key];
  const trVal = trMap[key];
  if (!trVal) {
    missing.push(key);
    continue;
  }
  if (MIRROR_KEY_ALLOW.has(key)) continue;
  if (enVal === trVal && /\s/.test(enVal) && enVal.length > 8 && !MIRROR_VALUE_ALLOW.test(enVal)) {
    mirrored.push(key);
  }
}

assert.equal(missing.length, 0, `Missing TR for keys: ${missing.slice(0, 20).join(", ")}${missing.length > 20 ? "…" : ""}`);
assert.equal(mirrored.length, 0, `TR mirrors EN for: ${mirrored.slice(0, 20).join(", ")}${mirrored.length > 20 ? "…" : ""}`);

const lines = keys.map((key) => {
  const value = trMap[key].replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `  "${key}": "${value}",`;
});

writeFileSync(
  trOut,
  `/** Auto-generated by scripts/build-settings-tr.mjs — do not edit by hand. */
import type { SettingsI18nKey } from "./settingsI18n";

export const settingsI18nTr: Record<SettingsI18nKey, string> = {
${lines.join("\n")}
};
`,
);

console.log("built settingsI18nTr.ts:", keys.length, "keys");
