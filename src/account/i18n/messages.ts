const catalogs: Record<AccountLocale, MessageTree> = { en, tr };

let activeLocale: AccountLocale = detectInitialLocale();

function detectInitialLocale(): AccountLocale {
  try {
    const stored = localStorage.getItem("picom.account.locale");
    if (stored === "tr" || stored === "en") return stored;
  } catch {
    // ignore
  }
  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en";
  return nav.startsWith("tr") ? "tr" : "en";
}

export function getLocale(): AccountLocale {
  return activeLocale;
}

export function setLocale(locale: AccountLocale): void {
  activeLocale = locale;
  try {
    localStorage.setItem("picom.account.locale", locale);
  } catch {
    // ignore
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
  }
}

export function t(key: string): string {
  const table = catalogs[activeLocale] ?? catalogs.en;
  return table[key] ?? catalogs.en[key] ?? key;
}

